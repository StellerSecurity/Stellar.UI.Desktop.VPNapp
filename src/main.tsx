import { createRoot } from 'react-dom/client';
import { App } from './app/App';
import { AppProvider } from './app/AppProvider';
import { createContainer } from './app/container';
import { ErrorBoundary } from './shared/ui/ErrorBoundary';
import '../stellar-tokens.css';
import '../vpn.css';
import './shared/design-system/desktop.css';
import { TrayApp } from './features/tray/ui/TrayApp';
import './features/tray/ui/tray.css';
import './features/connection/ui/compact-connection.css';
import { InstallationGate } from './features/setup/ui/InstallationGate';

const root = document.getElementById('root');
if (!root) throw new Error('Missing application root');
const container = createContainer();
const surface = new URLSearchParams(location.search).get('surface') === 'tray' ? 'tray' : 'main';
document.documentElement.classList.toggle('tray-surface', surface === 'tray');
const application = <AppProvider container={container} surface={surface}>{surface === 'tray' ? <TrayApp /> : <App />}</AppProvider>;
createRoot(root).render(<ErrorBoundary>{surface === 'main' ? <InstallationGate service={container.installation}>{application}</InstallationGate> : application}</ErrorBoundary>);
